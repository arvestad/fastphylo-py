"""Deterministic synthetic DNA/protein datasets for run_benchmarks.py.

Each dataset is a set of sequences generated by mutating a single random
ancestor along a star topology (independent per-taxon mutation, not a real
phylogeny) - not biologically realistic, but good enough for timing: it
gives every pairwise distance a plausible, non-degenerate value (not 0,
not fully saturated) without needing real data at every requested size.

Fixed seed (see SEED below): re-running this script regenerates byte-identical
FASTA files, so a benchmark report can always be reproduced from scratch.
"""

from __future__ import annotations

import random
from pathlib import Path

SEED = 20260812
DNA_ALPHABET = "ACGT"
PROTEIN_ALPHABET = "ARNDCQEGHILKMFPSTWYV"

OUT_DIR = Path(__file__).parent / "data"


def _mutate(ancestor: str, alphabet: str, rate: float, rng: random.Random) -> str:
    out = list(ancestor)
    for i in range(len(out)):
        if rng.random() < rate:
            out[i] = rng.choice(alphabet)
    return "".join(out)


def make_dataset(n_taxa: int, length: int, alphabet: str, mutation_rate: float, rng: random.Random) -> list[tuple[str, str]]:
    ancestor = "".join(rng.choice(alphabet) for _ in range(length))
    return [(f"t{i}", _mutate(ancestor, alphabet, mutation_rate, rng)) for i in range(n_taxa)]


def write_fasta(path: Path, records: list[tuple[str, str]]) -> None:
    with open(path, "w") as fh:
        for name, seq in records:
            fh.write(f">{name}\n{seq}\n")


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    rng = random.Random(SEED)

    # (n_taxa, seq_length, mutation_rate) - rate tuned so pairwise distances
    # stay in a realistic, non-saturated range at each length. The DNA path
    # is fast enough that n60/L300 sits under a millisecond - noise-dominated,
    # not a meaningful measurement - so a larger n200/L1000 tier is included
    # specifically to get a real signal for that path too.
    dna_specs = [(10, 300, 0.05), (30, 300, 0.05), (60, 300, 0.05), (200, 1000, 0.05)]
    protein_specs = [(10, 200, 0.08), (30, 200, 0.08), (60, 200, 0.08)]

    for n, length, rate in dna_specs:
        recs = make_dataset(n, length, DNA_ALPHABET, rate, rng)
        write_fasta(OUT_DIR / f"dna_n{n}.fasta", recs)

    for n, length, rate in protein_specs:
        recs = make_dataset(n, length, PROTEIN_ALPHABET, rate, rng)
        write_fasta(OUT_DIR / f"protein_n{n}.fasta", recs)

    print(f"Wrote {len(dna_specs)} DNA and {len(protein_specs)} protein datasets to {OUT_DIR}")


if __name__ == "__main__":
    main()
